"""Single-video summarization for CLIP and VL-JEPA encoders.

Samples evenly spaced clips from an uploaded video, scores each clip against a
bank of CCTV activity descriptions with the encoder's text tower (zero-shot),
and turns the per-segment activity timeline into a text summary. Answers to
user questions and model-vs-model comparisons are generated by the LLM from
those summaries only, so every answer is grounded in what the encoder saw.
"""

