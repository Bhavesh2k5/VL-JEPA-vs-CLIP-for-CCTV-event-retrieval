def format_ts(seconds: float) -> str:
    s = int(round(seconds))
    return f"{s // 60:02d}:{s % 60:02d}"


def probe_video(path) -> dict:
    cap = cv2.VideoCapture(str(path))
    if not cap.isOpened():
        raise RuntimeError(f"cannot open video: {path}")
    info = {
        "fps": float(cap.get(cv2.CAP_PROP_FPS)) or 25.0,
        "total_frames": int(cap.get(cv2.CAP_PROP_FRAME_COUNT)),
        "width": int(cap.get(cv2.CAP_PROP_FRAME_WIDTH)),
        "height": int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT)),
    }
    cap.release()
    if info["total_frames"] <= 0:
        cap = cv2.VideoCapture(str(path))
        count = 0
        while count < 4096:
            ok = cap.grab()
            if not ok:
                break
            count += 1
        cap.release()
        info["total_frames"] = count
    if info["total_frames"] <= 0:
        raise RuntimeError(f"video has no decodable frames: {path}")
    info["duration"] = info["total_frames"] / info["fps"]
    return info


def _read_frames(path, start_frame: int, n: int, total: int) -> np.ndarray:
    cap = cv2.VideoCapture(str(path))
    if not cap.isOpened():
        raise RuntimeError(f"cannot open video: {path}")
    wanted = np.clip(np.arange(start_frame, start_frame + n), 0, total - 1)
    frames = {}
    position = 0
    max_index = int(wanted.max())
    while position <= max_index:
        ok = cap.grab()
        if not ok:
            break
        if position in set(wanted.tolist()):
            ok, frame = cap.retrieve()
            if ok:
                frames[position] = frame
        position += 1
    cap.release()
    if not frames:
        raise RuntimeError(f"no frames decoded at {start_frame}")
    last = frames[max(frames)]
    arr = np.stack([cv2.cvtColor(frames.get(i, last), cv2.COLOR_BGR2RGB) for i in sorted(wanted.tolist())])
    return arr


def load_video_segments(path, num_segments=None, clip_frames=CLIP_FRAMES):
    info = probe_video(path)
    total = info["total_frames"]
    duration = info["duration"]
    if num_segments is None:
        num_segments = int(np.clip(round(duration / 5.0), MIN_SEGMENTS, MAX_SEGMENTS))
    num_segments = min(num_segments, max(1, total // max(1, clip_frames // 4)))
    n = min(clip_frames, total)
    starts = np.linspace(0, max(0, total - n), num_segments).astype(int)
    segments = []
    for i, start in enumerate(starts):
        rgb = _read_frames(path, int(start), n, total)
        segments.append({
            "index": i,
            "start": float(start / info["fps"]),
            "end": float(min(start + n, total) / info["fps"]),
            "tensor": frames_to_tensor(rgb, 224),
            "thumbnail": rgb[0],
        })
    return info, segments


def _activity_text_embs(encoder) -> tuple:
    labels = list(ACTIVITIES)
    prompts = [p for label in labels for p in ACTIVITIES[label]]
    embs = encoder.encode_text(prompts)
    text_embs = torch.stack([embs[idxs].mean(0) for idxs in np.split(np.arange(len(prompts)), np.cumsum([len(ACTIVITIES[l]) for l in labels])[:-1])])
    return labels, text_embs


def _activity_probs(video_emb: torch.Tensor, text_embs: torch.Tensor, temperature: float = 100.0) -> list:
    sims = (video_emb @ text_embs.T).squeeze(0)
    probs = torch.softmax(sims * temperature, dim=0)
    order = torch.argsort(probs, descending=True)
    return [(int(i), float(probs[i])) for i in order]


def _temporal_dynamics(embs: np.ndarray) -> dict:
    adjacent = [float(embs[i] @ embs[i + 1]) for i in range(len(embs) - 1)]
    clusters = []
    for i, e in enumerate(embs):
        best_ci, best_sim = None, 0.0
        for ci, (centroid, _) in enumerate(clusters):
            sim = float(e @ centroid)
            if sim > best_sim:
                best_ci, best_sim = ci, sim
        if best_ci is not None and best_sim >= 0.90:
            clusters[best_ci][1].append(i)
            members = embs[clusters[best_ci][1]]
            centroid = members.mean(axis=0)
            clusters[best_ci] = (centroid / np.linalg.norm(centroid), clusters[best_ci][1])
        else:
            clusters.append((e.copy(), [i]))
    lines = []
    if adjacent:
        lines.append(
            "Adjacent-segment visual similarity: "
            + ", ".join(f"seg {a + 1}-{a + 2}: {s:.2f}" for a, s in enumerate(adjacent))
            + "."
        )
    lines.append(
        f"{len(clusters)} distinct visual pattern(s): "
        + "; ".join(
            f"pattern {chr(65 + ci)} covers segments {[i + 1 for i in idxs]}"
            for ci, (_, idxs) in enumerate(clusters)
        )
        + "."
    )
    return {"n_patterns": len(clusters), "lines": lines}


ACTION_LABELS = {
    "physical fight", "chase / running", "vandalism", "sports action",
    "person down / fall", "weapon threat", "theft / break-in",
}


def summarize_video(encoder, encoder_name: str, video_path, num_segments=None, clip_frames=CLIP_FRAMES) -> dict:
    info, segments = load_video_segments(video_path, num_segments=num_segments, clip_frames=clip_frames)
    labels, text_embs = _activity_text_embs(encoder)
    text_embs = text_embs.float()
    unaligned = getattr(encoder, "native_vl", True) is False
    if unaligned:
        center = text_embs.mean(dim=0, keepdim=True)
        text_embs = torch.nn.functional.normalize(text_embs - center, dim=1)
    seg_sim_list = []
    seg_embs = []
    motion = []
    for seg in segments:
        emb = encoder.encode_video(seg["tensor"]).float()
        seg_embs.append(emb.squeeze(0).numpy())
        seg_sim_list.append((emb @ text_embs.T).squeeze(0))
        t = seg["tensor"].numpy()
        small = np.stack([cv2.resize(f.transpose(1, 2, 0), (24, 24)) for f in t])
        motion.append(float(np.abs(np.diff(small, axis=0)).mean()))
        seg.pop("tensor")
    sim_stack = torch.stack(seg_sim_list)
    if unaligned:
        sim_stack = sim_stack - sim_stack.mean(dim=0, keepdim=True)
        motion_norm = np.clip((np.array(motion) - 0.02) / 0.04, 0.0, 1.0)
        boost = torch.tensor(
            [
                (motion_norm[i] - 0.5) if labels[j] in ACTION_LABELS else (0.5 - motion_norm[i])
                for i in range(len(segments))
                for j in range(len(labels))
            ],
            dtype=sim_stack.dtype,
        ).view(sim_stack.shape) * 0.35
        sim_stack = sim_stack + boost
    per_label_scores = {label: [] for label in labels}
    for seg, sims in zip(segments, sim_stack):
        probs = torch.softmax(sims * 100.0, dim=0)
        order = torch.argsort(probs, descending=True)
        seg["ranked"] = [(labels[int(i)], float(probs[i])) for i in order]
        seg["top"] = seg["ranked"][:3]
        for i, p in enumerate(probs.tolist()):
            per_label_scores[labels[i]].append(p)
    overall = sorted(
        ((label, float(np.mean(scores))) for label, scores in per_label_scores.items()),
        key=lambda kv: kv[1], reverse=True,
    )
    result = {
        "model": encoder_name,
        "info": info,
        "segments": segments,
        "overall": overall,
        "dynamics": _temporal_dynamics(np.stack(seg_embs)),
    }
    result["summary_text"] = build_summary_text(result)
    return result


def build_summary_text(result: dict) -> str:
    info = result["info"]
    lines = [
        f"Video: {info['duration']:.1f}s, {info['width']}x{info['height']}, "
        f"{len(result['segments'])} analyzed segments (encoder: {result['model'].upper()})."
    ]
    for seg in result["segments"]:
        top = ", ".join(f"{label} ({p * 100:.0f}%)" for label, p in seg["top"])
        lines.append(f"Segment {seg['index'] + 1} ({format_ts(seg['start'])}-{format_ts(seg['end'])}): {top}.")
    dom = result["overall"][:3]
    lines.append(
        "Dominant activities across the whole video: "
        + ", ".join(f"{label} (avg {p * 100:.0f}%)" for label, p in dom)
        + "."
    )
    dynamics = result.get("dynamics")
    if dynamics:
        lines.append("Temporal structure (visual embeddings): " + " ".join(dynamics["lines"]))
    if result["model"] == "vljepa":
        lines.append(
            "Note: VL-JEPA activity labels combine bias-corrected embedding scores "
            "with motion-energy gating (unaligned V-JEPA-2/CLIP-text space, so treat "
            "the action-vs-calm split as the reliable signal); the temporal structure "
            "above comes from V-JEPA 2 embeddings alone."
        )
    return "\n".join(lines)


def build_story_context(result: dict) -> str:
    lines = [
        f"The video is {result['info']['duration']:.0f} seconds long and was analyzed in "
        f"{len(result['segments'])} consecutive segments."
    ]
    prev_top = None
    for seg in result["segments"]:
        label, p = seg["top"][0]
        if prev_top is not None and label != prev_top:
            lines.append(
                f"At {format_ts(seg['start'])} the activity changes: until then it was "
                f"{prev_top}, and now it becomes {label} ({p * 100:.0f}%)."
            )
        else:
            lines.append(f"From {format_ts(seg['start'])} to {format_ts(seg['end'])}: {label} ({p * 100:.0f}%).")
        prev_top = label
    patterns = result.get("dynamics", {}).get("n_patterns")
    if patterns == 1:
        lines.append(
            "The visual embeddings form one continuous pattern, so the same kind of "
            "activity continues through the whole video."
        )
    elif patterns:
        lines.append(
            f"The visual embeddings show {patterns} distinct visual patterns, so the "
            "scene or activity clearly changes at some point in the video."
        )
    return "\n".join(lines)


def _run_generation(narrator, prompt: str, max_new_tokens: int) -> str:
    if hasattr(narrator, "narrate"):
        return narrator.narrate(prompt, max_new_tokens=max_new_tokens)
    return narrator.generate_from_prompt(prompt, max_new_tokens=max_new_tokens).strip()


def story_narration(narrator, result: dict) -> str:
    context = build_story_context(result)
    prompt = (
        "Narrate what happens in this CCTV video as a short story in simple English, "
        "in chronological order. Base the story ONLY on the facts below. Start "
        "sentences with the time, for example: 'At 00:05 two people start fighting.' "
        "Mention the moment when the activity changes, for example: 'At 00:20 someone "
        "falls down.'\n\n"
        f"Facts:\n{context}\n\nStory:"
    )
    return _run_generation(narrator, prompt, max_new_tokens=220).strip()


def incident_narrative(narrator, result: dict) -> str:
    prompt = (
        "You are a CCTV incident analyst. Based only on the video analysis below, "
        "write a concise incident report of 3-4 sentences describing what happened.\n"
        f"{result['summary_text']}\nIncident report:"
    )
    return _run_generation(narrator, prompt, max_new_tokens=180).strip()


def answer_question(narrator, summary_text: str, question: str) -> str:
    prompt = (
        f"Answer the question based ONLY on the video-analysis context below. If the "
        f"context does not contain the answer, say the information is not available "
        f"in the video summary.\n\nContext:\n{summary_text}\n\nQuestion: {question}\n\nAnswer:"
    )
    return _run_generation(narrator, prompt, max_new_tokens=140).strip()


def compare_summaries(summ_a: dict, summ_b: dict, narrator=None) -> dict:
    seg_pairs = []
    match_count = 0
    for sa, sb in zip(summ_a["segments"], summ_b["segments"]):
        la, pa = sa["top"][0]
        lb, pb = sb["top"][0]
        match = la == lb
        match_count += int(match)
        seg_pairs.append({
            "window": f"{format_ts(sa['start'])}-{format_ts(sa['end'])}",
            "a": la, "a_p": pa, "b": lb, "b_p": pb, "match": match,
        })
    labels_a = {label for seg in summ_a["segments"] for label, _ in seg["ranked"][:3]}
    labels_b = {label for seg in summ_b["segments"] for label, _ in seg["ranked"][:3]}
    n = max(1, len(seg_pairs))
    result = {
        "top1_agreement": match_count / n,
        "per_segment": seg_pairs,
        "only_a": sorted(labels_a - labels_b),
        "only_b": sorted(labels_b - labels_a),
        "avg_conf_a": float(np.mean([seg["top"][0][1] for seg in summ_a["segments"]])),
        "avg_conf_b": float(np.mean([seg["top"][0][1] for seg in summ_b["segments"]])),
    }
    if narrator is not None:
        prompt = (
            "Two AI models summarized the same CCTV video. Compare the summaries and "
            "state the key differences in 2-3 short sentences.\n"
            f"{summ_a['model'].upper()} summary:\n{summ_a['summary_text']}\n\n"
            f"{summ_b['model'].upper()} summary:\n{summ_b['summary_text']}\n\nKey differences:"
        )
        result["llm_diff"] = _run_generation(narrator, prompt, max_new_tokens=160).strip()
    return result
